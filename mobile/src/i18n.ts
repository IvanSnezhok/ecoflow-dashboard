export type Language = 'uk' | 'en';
export type LanguageChoice = Language | 'auto';

const KEY = 'ecoflow.language';

/** Ukrainian for a phone set to Ukrainian, else English */
function deviceLanguage(): Language {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('uk') ? 'uk' : 'en';
  } catch {
    return 'en';
  }
}

interface LanguageStore {
  choice: LanguageChoice;
  language: Language;
  setChoice: (choice: LanguageChoice) => void;
  restore: () => Promise<void>;
}

export const useLanguage = create<LanguageStore>((set) => ({
  choice: 'auto',
  language: deviceLanguage(),
  setChoice: (choice) => {
    set({ choice, language: choice === 'auto' ? deviceLanguage() : choice });
    void writeItem(KEY, choice === 'auto' ? null : choice);
  },
  restore: async () => {
    const saved = await readItem(KEY);
    if (saved === 'uk' || saved === 'en') set({ choice: saved, language: saved });
  },
}));

export type Translate = (key: Key, params?: Record<string, string | number>) => string;

const translate = (language: Language): Translate => (key, params) => {
  const text = (language === 'uk' ? uk : en)[key] ?? en[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? '')) : text;
};

const translators: Record<Language, Translate> = { uk: translate('uk'), en: translate('en') };

/** The translator for the chosen language; components re-render when it changes */
export function useT(): Translate {
  return translators[useLanguage((s) => s.language)];
}

/** Outside components (stores, notifications) */
export const tNow: Translate = (key, params) => translators[useLanguage.getState().language](key, params);

/** BCP 47 tag for date formatting */
export const localeTag = (language: Language) => (language === 'uk' ? 'uk-UA' : 'en-GB');
